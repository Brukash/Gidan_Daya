// Downloads the two OFL families used by the interface and writes a local @font-face sheet.
// Source: Google Fonts CSS API (woff2, variable where available). Run: node scripts/fetch-fonts.mjs
import { mkdir, writeFile } from 'node:fs/promises';

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

const FAMILIES = [
  { name: 'Fraunces', query: 'family=Fraunces:opsz,wght@9..144,400..900', slug: 'fraunces' },
  { name: 'IBM Plex Sans', query: 'family=IBM+Plex+Sans:wght@400..700', slug: 'ibm-plex-sans' },
];

await mkdir('public/fonts', { recursive: true });

const faces = [];
const seen = new Map();

for (const family of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?${family.query}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${family.slug}: CSS ${res.status}`);
  const css = await res.text();

  const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*{([^}]+)}/g)];
  if (blocks.length === 0) throw new Error(`${family.slug}: no @font-face blocks`);

  for (const [, subset, body] of blocks) {
    if (subset !== 'latin') continue;

    const weight = /font-weight:\s*([^;]+);/.exec(body)?.[1]?.trim() ?? '400';
    const style = /font-style:\s*([^;]+);/.exec(body)?.[1]?.trim() ?? 'normal';
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1]?.trim();
    const src = /src:\s*url\((https:[^)]+\.woff2)\)/.exec(body)?.[1];
    if (!src) continue;

    // Google may serve the same variable file for several weight requests; keep one copy.
    let file = seen.get(src);
    if (!file) {
      file = `${family.slug}-${weight.replace(/[\s.]+/g, '-')}-${style}.woff2`;
      const bin = await fetch(src, { headers: { 'User-Agent': UA } });
      if (!bin.ok) throw new Error(`${family.slug} ${file}: ${bin.status}`);
      await writeFile(`public/fonts/${file}`, Buffer.from(await bin.arrayBuffer()));
      seen.set(src, file);
      console.log(`saved public/fonts/${file} (${weight} ${style})`);
    }

    faces.push(
      [
        '@font-face {',
        `  font-family: '${family.name}';`,
        `  font-style: ${style};`,
        `  font-weight: ${weight};`,
        '  font-display: swap;',
        `  src: url('/fonts/${file}') format('woff2');`,
        ...(range ? [`  unicode-range: ${range};`] : []),
        '}',
      ].join('\n'),
    );
  }
}

await writeFile(
  'src/styles/fonts.css',
  `/* Generated by scripts/fetch-fonts.mjs. Fraunces and IBM Plex Sans, SIL Open Font License 1.1. */\n\n${faces.join('\n\n')}\n`,
);
console.log(`wrote src/styles/fonts.css (${faces.length} faces, ${seen.size} files)`);
